void
SoRTXRenderBackend::teardownRtxDenoiser()
{
#if COIN_BUILD_RTX_DENOISER
  // Report a CUDA/OptiX teardown failure (both use 0 for success) without
  // aborting the remaining cleanup.
  auto reportTeardown = [this](const char * what, int res) {
    if (res == 0) return;
    char msg[192];
    std::snprintf(msg, sizeof(msg),
                  "RTX denoiser teardown: %s failed (result %d)", what, res);
    this->emitError(msg);
  };
  // CUDA driver memory operations act on the current context, so make ours
  // current before freeing the denoiser-owned allocations.
  if (this->rtxCudaCtx) {
    reportTeardown("cuCtxSetCurrent",
                   static_cast<int>(cuCtxSetCurrent(this->rtxCudaCtx)));
  }
  if (this->rtxStream) {
    reportTeardown("cuStreamSynchronize",
                   static_cast<int>(cuStreamSynchronize(this->rtxStream)));
  }
  if (this->rtxInteropSemaphoresReady || this->rtxVkToCudaSem != VK_NULL_HANDLE ||
      this->rtxCudaToVkSem != VK_NULL_HANDLE ||
      this->rtxVkToCudaCudaSem != nullptr ||
      this->rtxCudaToVkCudaSem != nullptr) {
    this->destroyRtxInteropSemaphore(this->rtxVkToCudaSem,
                                     this->rtxVkToCudaCudaSem, true);
    this->destroyRtxInteropSemaphore(this->rtxCudaToVkSem,
                                     this->rtxCudaToVkCudaSem, true);
  }
  this->rtxInteropSemaphoresReady = false;
  this->rtxVkToCudaSignalPending = false;
  this->rtxCudaSignalPending = false;
  if (this->rtxDenoiser) {
    reportTeardown("optixDenoiserDestroy",
                   static_cast<int>(optixDenoiserDestroy(this->rtxDenoiser)));
    this->rtxDenoiser = nullptr;
  }
  if (this->rtxDeviceContext) {
    reportTeardown(
      "optixDeviceContextDestroy",
      static_cast<int>(optixDeviceContextDestroy(this->rtxDeviceContext)));
    this->rtxDeviceContext = nullptr;
  }
  if (this->rtxNormModule) {
    reportTeardown("cuModuleUnload",
                   static_cast<int>(cuModuleUnload(this->rtxNormModule)));
    this->rtxNormModule = nullptr;
    this->rtxNormKernel = nullptr;
  }
  if (this->rtxIntensity) { cuMemFree(this->rtxIntensity); this->rtxIntensity = 0; }
  if (this->rtxState) { cuMemFree(this->rtxState); this->rtxState = 0; }
  if (this->rtxScratch) { cuMemFree(this->rtxScratch); this->rtxScratch = 0; }

  // The four working images were exported from Vulkan and imported into CUDA.
  // Reverse the import (release the CUDA alias) BEFORE freeing the Vulkan
  // allocation that owns the memory.
  auto releaseInterop = [this, &reportTeardown](VkBuffer & buf, VmaAllocation & mem,
                               CUexternalMemory & ext) {
    if (ext) {
      reportTeardown("cuDestroyExternalMemory",
                     static_cast<int>(cuDestroyExternalMemory(ext)));
      ext = nullptr;
    }
    const VkBuffer vkBuf = buf;
    const VmaAllocation vkMem = mem;
    buf = VK_NULL_HANDLE;
    mem = VK_NULL_HANDLE;
    if (vkBuf != VK_NULL_HANDLE || vkMem != VK_NULL_HANDLE) {
      this->deferDestroy([this, vkBuf, vkMem]() {
        vmaDestroyBuffer(this->vmaAllocator, vkBuf, vkMem);
      });
    }
  };
  releaseInterop(this->rtxColorVk, this->rtxColorMem, this->rtxColorExt);
  releaseInterop(this->rtxAlbedoVk, this->rtxAlbedoMem, this->rtxAlbedoExt);
  releaseInterop(this->rtxNormalVk, this->rtxNormalMem, this->rtxNormalExt);
  releaseInterop(this->rtxMotionVk, this->rtxMotionMem, this->rtxMotionExt);
  releaseInterop(this->rtxOutputVk, this->rtxOutputMem, this->rtxOutputExt);
  this->rtxColorImage = 0;
  this->rtxAlbedoImage = 0;
  this->rtxNormalImage = 0;
  this->rtxMotionImage = 0;
  this->rtxOutputImage = 0;
  this->rtxInteropReady = false;

  if (this->rtxStream) {
    reportTeardown("cuStreamDestroy",
                   static_cast<int>(cuStreamDestroy(this->rtxStream)));
    this->rtxStream = nullptr;
  }
  if (this->rtxCudaCtx) {
    reportTeardown("cuCtxDestroy",
                   static_cast<int>(cuCtxDestroy(this->rtxCudaCtx)));
    this->rtxCudaCtx = nullptr;
  }
#endif
}

