// NVIDIA RTX denoiser backend ("rtx" slot): the OptiX + CUDA half of the
// denoise concern split out of SoRTXRenderBackendDenoise.cpp.  It owns the
// CUDA context/stream, the OptiX device context and AOV denoiser, the
// CUDA-Vulkan external-memory/semaphore interop that lets the OptiX kernel
// read the path tracer's G-buffers and write the denoised output in place,
// and the embedded PTX normalizer kernel.  All of it is compiled out when
// COIN_BUILD_RTX_DENOISER=0; the declarations in SoRTXRenderBackend.h stay
// present so the dispatch in SoRTXRenderBackendDenoise.cpp links either way.
//
